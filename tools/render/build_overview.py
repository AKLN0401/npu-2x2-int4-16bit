"""Embed the layout images and the 3D model into docs/overview.html (one self-contained file).

Replaces everything between the ASSETS:BEGIN / ASSETS:END markers (before </body>) with one <script>:
the images as WebP data URIs (<img data-asset="key">), the gzipped 3D model, viewer3d.js and the init code
for <div id="gds3d">. Run tools/render/render_all.sh first (it renders the PNGs and calls this script).

Usage: python build_overview.py <overview.html> <gds> <render dir>
"""
import base64
import io
import json
import os
import re
import sys

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen3d  # noqa: E402

# key: (png in the render dir, width px, WebP quality)
IMAGES = {
    "gds":     ("npu1x1_gds.png", 1400, 62),
    "routing": ("npu1x1_routing.png", 1400, 66),
    "close3d": ("shot_close.png", 1400, 75),
    "iso3d":   ("shot_iso.png", 1400, 75),
}
BEGIN, END = "<!-- ASSETS:BEGIN", "<!-- ASSETS:END -->"


def webp(path, width, q):
    im = Image.open(path).convert("RGB")
    if im.width > width:
        im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
    b = io.BytesIO()
    im.save(b, "WEBP", quality=q, method=6)
    return "data:image/webp;base64," + base64.b64encode(b.getvalue()).decode()


def main(page, gds, rdir):
    assets = {k: webp(os.path.join(rdir, f), w, q) for k, (f, w, q) in IMAGES.items()}
    meta = gen3d.encode(gds, "tt_um_akln0401_npu · GDS")
    js = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "viewer3d.js")).read()
    block = f"""{BEGIN} (generated by tools/render/build_overview.py — do not edit by hand) -->
<script>
const ASSETS = {json.dumps(assets)};
const GDS3D = {json.dumps(meta)};
{js}
document.querySelectorAll("img[data-asset]").forEach(i => {{ i.src = ASSETS[i.dataset.asset]; }});
(() => {{
  const el = document.getElementById("gds3d");
  if (!el) return;
  const start = () => initGds3D(el, GDS3D, {{ poster: ASSETS.iso3d }});
  if (!("IntersectionObserver" in window)) return start();
  const io = new IntersectionObserver(es => {{ if (es.some(e => e.isIntersecting)) {{ io.disconnect(); start(); }} }}, {{ rootMargin: "300px" }});
  io.observe(el);
}})();
</script>
{END}"""
    html = open(page).read()
    if BEGIN in html:
        html = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, html, flags=re.S)
    else:
        html = html.replace("</body>", block + "\n</body>")
    open(page, "w").write(html)
    sizes = ", ".join(f"{k} {len(v) * 3 / 4 / 1e3:.0f} KB" for k, v in assets.items())
    print(f"{page}: {len(html) / 1e6:.2f} MB ({sizes}; 3D model "
          f"{sum(len(L['data']) for L in meta['layers']) * 3 / 4 / 1e3:.0f} KB)")


if __name__ == "__main__":
    main(*sys.argv[1:4])
